#!/usr/bin/env bash
# Compose each profile's SOUL.md from the shared core rules and sync core skills.
#
#   SOUL.md            = hermes-core/SOUL.base.md + <profile>/SOUL.local.md
#   skills/core/*      = copy of hermes-core/skills/*   (overwritten every build)
#
# Usage:
#   scripts/build.sh --all                 # every hermes-* sibling folder except hermes-core
#   scripts/build.sh ../hermes-percy ...   # specific profile folders
#
# Compatible with the macOS default bash (3.2).
set -euo pipefail

CORE_DIR="$(cd "$(dirname "$0")/.." && pwd)"
ROOT_DIR="$(cd "$CORE_DIR/.." && pwd)"
BASE_SOUL="$CORE_DIR/SOUL.base.md"
CORE_SKILLS="$CORE_DIR/skills"
CORE_VERSION="$(git -C "$CORE_DIR" rev-parse --short HEAD 2>/dev/null || echo "uncommitted")"

usage() { awk 'NR>1 && /^#/{sub(/^# ?/,"");print;next} NR>1{exit}' "$0"; exit 1; }
[ $# -eq 0 ] && usage

targets=()
if [ "$1" = "--all" ]; then
  for d in "$ROOT_DIR"/hermes-*; do
    [ -d "$d" ] || continue
    [ "$(basename "$d")" = "hermes-core" ] && continue
    [ -f "$d/SOUL.local.md" ] || { echo "skip $(basename "$d") (no SOUL.local.md)"; continue; }
    targets+=("$d")
  done
else
  for d in "$@"; do targets+=("$(cd "$d" && pwd)"); done
fi

[ ${#targets[@]} -eq 0 ] && { echo "No profile folders found."; exit 1; }

for dir in "${targets[@]}"; do
  name="$(basename "$dir")"
  local_soul="$dir/SOUL.local.md"
  [ -f "$local_soul" ] || { echo "ERROR: $local_soul not found" >&2; exit 1; }

  {
    echo "<!-- GENERATED by hermes-core/scripts/build.sh (core @ $CORE_VERSION). Do not edit."
    echo "     Edit hermes-core/SOUL.base.md or SOUL.local.md and rebuild. -->"
    echo
    # Strip the HTML comment header from the base file.
    awk 'BEGIN{c=0} /^<!--/{c=1} c==0{print} /-->/{c=0}' "$BASE_SOUL" | sed '/./,$!d'
    echo
    echo "---"
    echo
    cat "$local_soul"
  } > "$dir/SOUL.md"

  mkdir -p "$dir/skills"
  rm -rf "$dir/skills/core"
  cp -R "$CORE_SKILLS" "$dir/skills/core"

  echo "built $name  (SOUL.md + skills/core from core @ $CORE_VERSION)"
done
